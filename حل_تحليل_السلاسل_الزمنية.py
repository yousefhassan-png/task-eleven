
# %% ---------------------- استدعاء المكتبات ----------------------
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# إعداد الخط عشان تظهر الحروف العربية بالرسومات (Tahoma و Arial موجودين بويندوز)
plt.rcParams['font.family'] = 'sans-serif'
plt.rcParams['font.sans-serif'] = ['Tahoma', 'Arial', 'DejaVu Sans']
plt.rcParams['axes.unicode_minus'] = False

# دالة صغيرة تعدّل شكل النص العربي ليظهر صحيحًا بالرسمة (الحروف متصلة ومن اليمين لليسار)
# إذا المكتبتين مش مثبتتين بيظل النص كما هو بدون أي خطأ
try:
    import arabic_reshaper
    from bidi.algorithm import get_display

    def عربي(نص):
        return get_display(arabic_reshaper.reshape(نص))
except ImportError:
    def عربي(نص):
        return نص

# أسماء الأشهر وأيام الأسبوع بالعربي (نستخدمها بالعناوين وبالتسميات)
أسماء_الأشهر = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو',
                'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر']

أيام_بالعربي = {'Monday': 'الاثنين', 'Tuesday': 'الثلاثاء', 'Wednesday': 'الأربعاء',
                'Thursday': 'الخميس', 'Friday': 'الجمعة', 'Saturday': 'السبت',
                'Sunday': 'الأحد'}


# %% =====================================================================
# الجزء 1 — التعامل مع التاريخ والوقت بـ Pandas
# =====================================================================

# --- تجهيز البيانات المصطنعة (مبيعات يومية لسنتين) ---
np.random.seed(42)  # نثبّت الرقم العشوائي عشان النتائج تكون نفسها كل مرة
التواريخ = pd.date_range(start='2023-01-01', end='2024-12-31', freq='D')

# مبيعات عشوائية بين 500 و 2000، ونضيف 800 على شهري 11 و 12 (موسم الأعياد)
المبيعات = np.random.randint(500, 2000, size=len(التواريخ)) + \
    np.where(pd.Series(التواريخ).dt.month.isin([11, 12]), 800, 0)

مبيعات_يومية = pd.DataFrame({'التاريخ': التواريخ, 'المبيعات': المبيعات})

print('=' * 60)
print('الجزء 1 — أول 5 صفوف من البيانات')
print(مبيعات_يومية.head())

# --- التمرين 1: التأكد أن عمود التاريخ من نوع datetime ---
print('\n--- التمرين 1: نوع عمود التاريخ ---')
print('نوع العمود قبل أي تحويل:', مبيعات_يومية['التاريخ'].dtype)

# نحوّله بـ pd.to_datetime للتأكيد (لو كان datetime أصلًا ما بيتغيّر شي)
مبيعات_يومية['التاريخ'] = pd.to_datetime(مبيعات_يومية['التاريخ'])
print('نوع العمود بعد pd.to_datetime:', مبيعات_يومية['التاريخ'].dtype)
print('النتيجة: العمود من نوع datetime64 فعليًا وليس نص.')

# --- التمرين 2: استخراج أعمدة جديدة (سنة، شهر، يوم الأسبوع) ---
print('\n--- التمرين 2: استخراج السنة والشهر واليوم ---')
مبيعات_يومية['السنة'] = مبيعات_يومية['التاريخ'].dt.year
مبيعات_يومية['الشهر'] = مبيعات_يومية['التاريخ'].dt.month
# day_name() بيعطي اسم اليوم بالإنجليزي، فنحوّله للعربي بالقاموس
مبيعات_يومية['يوم_الأسبوع'] = مبيعات_يومية['التاريخ'].dt.day_name().map(أيام_بالعربي)
print(مبيعات_يومية.head(10))

# --- التمرين 3: تعيين التاريخ كـ Index ---
print('\n--- التمرين 3: تعيين التاريخ كـ Index ---')
مبيعات_يومية = مبيعات_يومية.set_index('التاريخ')
print(مبيعات_يومية.head())
print('نوع الـ Index الآن:', type(مبيعات_يومية.index).__name__)

# --- التمرين 4: عرض بيانات شهر معيّن (نوفمبر 2023) ---
print('\n--- التمرين 4: بيانات نوفمبر 2023 ---')
بيانات_نوفمبر_2023 = مبيعات_يومية.loc['2023-11']
print(بيانات_نوفمبر_2023)
print('عدد الأيام:', len(بيانات_نوفمبر_2023))
print('مجموع مبيعات نوفمبر 2023:', بيانات_نوفمبر_2023['المبيعات'].sum())


# %% =====================================================================
# الجزء 2 — Resampling: تلخيص البيانات بمستويات زمنية مختلفة
# =====================================================================
print('\n' + '=' * 60)
print('الجزء 2 — Resampling')

# --- التمرين 1: مبيعات أسبوعية + Line Chart ---
# 'W' = أسبوعي (ينتهي الأسبوع يوم الأحد)
مبيعات_أسبوعية = مبيعات_يومية['المبيعات'].resample('W').sum()
print('\nأول 5 أسابيع:')
print(مبيعات_أسبوعية.head())
print('ملاحظة: أول أسبوع فيه يوم واحد فقط (1 يناير 2023 كان أحد) وآخر أسبوع ناقص،')
print('فمجموعهم أقل من باقي الأسابيع، وهذا طبيعي وليس خطأ.')

plt.figure(figsize=(11, 4))
plt.plot(مبيعات_أسبوعية.index, مبيعات_أسبوعية.values, color='steelblue')
plt.title(عربي('المبيعات الأسبوعية (2023 - 2024)'))
plt.xlabel(عربي('التاريخ'))
plt.ylabel(عربي('مجموع المبيعات الأسبوعية'))
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# --- التمرين 2: مبيعات شهرية + Line Chart ---
# 'ME' = Month End (نهاية الشهر). بالنسخ القديمة من pandas كان الرمز 'M'
مبيعات_شهرية = مبيعات_يومية['المبيعات'].resample('ME').sum()
print('\nالمبيعات الشهرية:')
print(مبيعات_شهرية)

plt.figure(figsize=(11, 4))
plt.plot(مبيعات_شهرية.index, مبيعات_شهرية.values, marker='o', color='darkgreen')
plt.title(عربي('المبيعات الشهرية (2023 - 2024)'))
plt.xlabel(عربي('التاريخ'))
plt.ylabel(عربي('مجموع المبيعات الشهرية'))
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# مقارنة الوضوح بين الرسمتين
print('\n--- مقارنة وضوح النمط ---')
print(f'عدد النقاط بالرسمة الأسبوعية: {len(مبيعات_أسبوعية)}')
print(f'عدد النقاط بالرسمة الشهرية: {len(مبيعات_شهرية)}')
print('التفسير: الرسمة الأسبوعية فيها 106 نقطة وخطها متعرّج بسبب التذبذب العشوائي')
print('من أسبوع لأسبوع، ورغم إن الارتفاع بنهاية السنة بيبان فيها، النمط أقل وضوحًا.')
print('أما الشهرية فنقاطها 24 فقط والخط أنعم، فقفزة نوفمبر وديسمبر بتظهر بوضوح')
print('أكبر بكلا السنتين، وبنقدر نقارن السنتين بسهولة.')

# --- التمرين 3: متوسط المبيعات اليومية لكل شهر ---
متوسط_يومي_شهري = مبيعات_يومية['المبيعات'].resample('ME').mean()
print('\nمتوسط المبيعات اليومية لكل شهر:')
print(متوسط_يومي_شهري.round(1))

print('\nمثال للفرق (يناير 2023 مقابل فبراير 2023):')
print(f'  مجموع يناير 2023  = {مبيعات_شهرية.iloc[0]}  (31 يوم)')
print(f'  مجموع فبراير 2023 = {مبيعات_شهرية.iloc[1]}  (28 يوم)')
print(f'  متوسط يناير 2023  = {متوسط_يومي_شهري.iloc[0]:.1f}')
print(f'  متوسط فبراير 2023 = {متوسط_يومي_شهري.iloc[1]:.1f}')
print('الفرق بالمعنى:')
print('- المجموع الشهري = كم بعنا بالشهر كله، وبيتأثر بعدد أيام الشهر')
print('  (الشهر الأطول بيطلع مجموعه أكبر حتى لو الأداء نفسه).')
print('- متوسط اليوم = كم بنبيع بالأداء المعتاد باليوم الواحد، وهو أعدل للمقارنة')
print('  بين شهر 28 يوم وشهر 31 يوم.')

# --- التمرين 4: متى نفضّل التلخيص لمستوى أوسع؟ (جملتين) ---
print('\n--- التمرين 4: متى نفضّل التلخيص لمستوى أوسع؟ ---')
print('نفضّل التلخيص (شهري مثلًا) لما نبدي نشوف الصورة الكبيرة والأنماط الطويلة')
print('(اتجاه، موسمية) لأنه بيخفي الضجيج والتذبذب العشوائي اليومي.')
print('أما التحليل اليومي فنحتاجه لما نبحث عن تفاصيل دقيقة مثل يوم معيّن أو')
print('عطلة نهاية أسبوع، لأن التلخيص بيخفي هاي التفاصيل.')


# %% =====================================================================
# الجزء 3 — اكتشاف الاتجاه والموسمية
# =====================================================================
print('\n' + '=' * 60)
print('الجزء 3 — الاتجاه والموسمية')

# --- التمرين 1: هل في اتجاه عام؟ ---
plt.figure(figsize=(11, 4))
plt.plot(مبيعات_شهرية.index, مبيعات_شهرية.values, marker='o', color='darkgreen',
         label=عربي('المبيعات الشهرية'))

# نضيف خط اتجاه بسيط (خط مستقيم) لنشوف الميل العام
الرقم_التسلسلي = np.arange(len(مبيعات_شهرية))
ميل, نقطة_التقاطع = np.polyfit(الرقم_التسلسلي, مبيعات_شهرية.values, 1)
plt.plot(مبيعات_شهرية.index, ميل * الرقم_التسلسلي + نقطة_التقاطع,
         color='red', linestyle='--', label=عربي('خط الاتجاه العام'))

plt.title(عربي('المبيعات الشهرية عبر السنتين مع خط الاتجاه'))
plt.xlabel(عربي('التاريخ'))
plt.ylabel(عربي('مجموع المبيعات الشهرية'))
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

مجموع_2023 = مبيعات_يومية.loc['2023', 'المبيعات'].sum()
مجموع_2024 = مبيعات_يومية.loc['2024', 'المبيعات'].sum()
نسبة_التغير = (مجموع_2024 - مجموع_2023) / مجموع_2023 * 100
print(f'\nمجموع مبيعات 2023: {مجموع_2023}')
print(f'مجموع مبيعات 2024: {مجموع_2024}')
print(f'نسبة التغير بين السنتين: {نسبة_التغير:.2f}%')

# نقارن الأشهر العادية فقط (1 إلى 10) عشان نستبعد تأثير موسم الأعياد
عادي_2023 = مبيعات_يومية.loc['2023-01':'2023-10', 'المبيعات'].mean()
عادي_2024 = مبيعات_يومية.loc['2024-01':'2024-10', 'المبيعات'].mean()
print(f'متوسط المبيعات اليومية (يناير-أكتوبر) 2023: {عادي_2023:.1f}')
print(f'متوسط المبيعات اليومية (يناير-أكتوبر) 2024: {عادي_2024:.1f}')
print(f'نسبة التغير بالأشهر العادية: {(عادي_2024 - عادي_2023) / عادي_2023 * 100:.2f}%')
print(f'ميل خط الاتجاه: {ميل:.0f} وحدة لكل شهر')
print('الاستنتاج: ما في اتجاه عام واضح. المبيعات شبه مستقرة بين السنتين،')
print('والفرق الصغير سببه التذبذب العشوائي (مثلًا ديسمبر 2024 طلع أعلى من ديسمبر 2023)،')
print('وخط الاتجاه الأحمر بيميل شوي لفوق لأن آخر شهر بالبيانات (ديسمبر 2024) مرتفع.')
print('الارتفاعات اللي بنشوفها بنهاية كل سنة هي موسمية وليست اتجاه عام.')

# --- التمرين 2: GroupBy حسب الشهر بغض النظر عن السنة ---
متوسط_حسب_الشهر = مبيعات_يومية.groupby(مبيعات_يومية.index.month)['المبيعات'].mean()
print('\n--- متوسط المبيعات اليومية لكل شهر (بغض النظر عن السنة) ---')
print(متوسط_حسب_الشهر.round(1))

متوسط_باقي_الأشهر = متوسط_حسب_الشهر.drop([11, 12]).mean()
متوسط_نوفمبر_وديسمبر = متوسط_حسب_الشهر.loc[[11, 12]].mean()
print(f'\nمتوسط باقي الأشهر (1 إلى 10): {متوسط_باقي_الأشهر:.1f}')
print(f'متوسط نوفمبر وديسمبر: {متوسط_نوفمبر_وديسمبر:.1f}')
print(f'نوفمبر وديسمبر أعلى بحوالي {متوسط_نوفمبر_وديسمبر - متوسط_باقي_الأشهر:.0f} وحدة '
      f'({(متوسط_نوفمبر_وديسمبر / متوسط_باقي_الأشهر - 1) * 100:.0f}%).')
print('الإجابة: نعم، نوفمبر وديسمبر أعلى بشكل ملحوظ، وهذا هو النمط الموسمي.')

# --- التمرين 3: Bar Chart للمتوسط الشهري ---
ألوان = ['tomato' if شهر in (11, 12) else 'lightsteelblue' for شهر in متوسط_حسب_الشهر.index]

plt.figure(figsize=(11, 5))
plt.bar(range(1, 13), متوسط_حسب_الشهر.values, color=ألوان)
plt.xticks(range(1, 13), [عربي(اسم) for اسم in أسماء_الأشهر], rotation=45)
plt.title(عربي('متوسط المبيعات اليومية لكل شهر (بغض النظر عن السنة)'))
plt.xlabel(عربي('الشهر'))
plt.ylabel(عربي('متوسط المبيعات اليومية'))
plt.grid(True, axis='y', alpha=0.3)
plt.tight_layout()
plt.show()
print('\nالإجابة: نعم، الرسمة بتأكد وجود موسمية واضحة، العمودان الأحمران')
print('(شهر 11 و 12) أعلى بوضوح من باقي الأعمدة.')

# --- التمرين 4: الفرق بين الاتجاه العام والموسمية (فقرة 3-4 جمل) ---
print('\n--- التمرين 4: الفرق بين الاتجاه العام (Trend) والموسمية (Seasonality) ---')
print('الاتجاه العام هو الحركة طويلة الأمد للبيانات: صعود أو هبوط أو استقرار')
print('على مدى سنوات، مثل نمو المبيعات سنة بعد سنة.')
print('أما الموسمية فهي نمط يتكرر بنفس الشكل بنفس الفترة من كل سنة، مثل ارتفاع')
print('المبيعات كل نوفمبر وديسمبر بسبب الأعياد، بغض النظر عن الاتجاه.')
print('نعم، ممكن يجتمعوا بنفس البيانات: مثلًا شركة مبيعاتها تنمو سنة بعد سنة')
print('(اتجاه تصاعدي) ومع ذلك كل سنة بتقفز بنهايتها (موسمية)، وبيانات الطيران')
print('بالجزء 4 مثال حقيقي على هذا.')
print('بيانات المبيعات المصطنعة هون فيها موسمية فقط بدون اتجاه عام.')


# %% =====================================================================
# الجزء 4 — تطبيق كامل على بيانات حقيقية (Flights)
# =====================================================================
print('\n' + '=' * 60)
print('الجزء 4 — بيانات ركاب الطيران (Flights)')

رحلات = sns.load_dataset('flights')
# نغيّر أسماء الأعمدة للعربي
رحلات = رحلات.rename(columns={'year': 'السنة', 'month': 'الشهر', 'passengers': 'الركاب'})
print(رحلات.head())
print('\nعدد الصفوف:', len(رحلات))

# --- التمرين 1: دمج السنة والشهر بعمود تاريخ واحد وتعيينه كـ Index ---
# الشهر مكتوب كاختصار إنجليزي (Jan, Feb...) فنحوّله لنص ثم نركّبه مع السنة
رحلات['التاريخ'] = pd.to_datetime(
    رحلات['السنة'].astype(str) + '-' + رحلات['الشهر'].astype(str),
    format='%Y-%b'
)
رحلات = رحلات.set_index('التاريخ')
print('\n--- التمرين 1: بعد الدمج وتعيين الـ Index ---')
print(رحلات.head())
print('نوع الـ Index:', type(رحلات.index).__name__)

# --- التمرين 2: رسم عدد الركاب عبر السنوات ---
plt.figure(figsize=(11, 4))
plt.plot(رحلات.index, رحلات['الركاب'], color='navy')
plt.title(عربي('عدد ركاب الطيران الشهري (1949 - 1960)'))
plt.xlabel(عربي('التاريخ'))
plt.ylabel(عربي('عدد الركاب (بالآلاف)'))
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

ركاب_أول_سنة = رحلات.loc['1949', 'الركاب'].mean()
ركاب_آخر_سنة = رحلات.loc['1960', 'الركاب'].mean()
print('\n--- التمرين 2: الاتجاه العام ---')
print(f'متوسط الركاب الشهري سنة 1949: {ركاب_أول_سنة:.1f} ألف')
print(f'متوسط الركاب الشهري سنة 1960: {ركاب_آخر_سنة:.1f} ألف')
print(f'الزيادة: حوالي {ركاب_آخر_سنة / ركاب_أول_سنة:.1f} ضعف')
print('الاتجاه العام: تصاعدي بوضوح. ونلاحظ كمان إن التذبذب الموسمي (الفرق بين')
print('القمة والقاع كل سنة) بيكبر مع الوقت.')

# --- التمرين 3: GroupBy حسب الشهر (بغض النظر عن السنة) ---
متوسط_الركاب_حسب_الشهر = رحلات.groupby(رحلات.index.month)['الركاب'].mean()
print('\n--- التمرين 3: متوسط الركاب لكل شهر (بغض النظر عن السنة) ---')
print(متوسط_الركاب_حسب_الشهر.round(1))

رقم_الأعلى = متوسط_الركاب_حسب_الشهر.idxmax()
رقم_الأقل = متوسط_الركاب_حسب_الشهر.idxmin()
print(f'\nالشهر الأعلى: {أسماء_الأشهر[رقم_الأعلى - 1]} (شهر {رقم_الأعلى}) '
      f'بمتوسط {متوسط_الركاب_حسب_الشهر.max():.1f} ألف راكب')
print(f'الشهر الأقل: {أسماء_الأشهر[رقم_الأقل - 1]} (شهر {رقم_الأقل}) '
      f'بمتوسط {متوسط_الركاب_حسب_الشهر.min():.1f} ألف راكب')
print('التفسير: يوليو وأغسطس هم أعلى شهور (عطلة الصيف والسفر)، ونوفمبر أقل شهر.')

ألوان_الطيران = []
for شهر in متوسط_الركاب_حسب_الشهر.index:
    if شهر == رقم_الأعلى:
        ألوان_الطيران.append('tomato')
    elif شهر == رقم_الأقل:
        ألوان_الطيران.append('seagreen')
    else:
        ألوان_الطيران.append('lightsteelblue')

plt.figure(figsize=(11, 5))
plt.bar(range(1, 13), متوسط_الركاب_حسب_الشهر.values, color=ألوان_الطيران)
plt.xticks(range(1, 13), [عربي(اسم) for اسم in أسماء_الأشهر], rotation=45)
plt.title(عربي('متوسط عدد الركاب لكل شهر (بغض النظر عن السنة)'))
plt.xlabel(عربي('الشهر'))
plt.ylabel(عربي('متوسط عدد الركاب (بالآلاف)'))
